"""Android vector drawables of the R-045 wordmark (navy letters, the i's blue square), for palette C (R-059/R-060).

Reads raviga-logo-final/wordmark/raviga-wordmark-transparent.svg and cuts it tight as iOS does (viewBox 0 64 523 194):
  res/drawable/ic_wordmark.xml      the wordmark, 92dp wide (Compose scales it: Welcome shows it 23dp tall)
  res/drawable/ic_splash_wordmark.xml  the launch screen: the wordmark 92dp wide, centred on the 288dp splash icon canvas

    .venv/bin/python -I tools/wordmark_vectors.py [path/to/raviga-wordmark-transparent.svg]
"""
import re, sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / "Downloads/raviga-logo-final/wordmark/raviga-wordmark-transparent.svg")
RES = Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"
NAVY, BLUE = "#14183A", "#6F8CFF"
COLOURS = {NAVY: "@color/mark_navy", BLUE: "@color/mark_blue"}
X0, Y0, VW, VH = 0, 64, 523, 194     # iOS's tight cut
WIDTH_DP = 92


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def paths(svg):
    out = []
    for tag in re.findall(r"<(?:path|circle|rect|polygon)\b[^>]*/>", svg):
        a, kind = attrs(tag), tag[1:].split()[0]
        if kind == "path":
            d = a["d"]
        elif kind == "circle":
            cx, cy, r = (float(a[k]) for k in ("cx", "cy", "r"))
            d = f"M{cx - r:g},{cy:g} a{r:g},{r:g} 0 1,0 {2 * r:g},0 a{r:g},{r:g} 0 1,0 {-2 * r:g},0 z"
        elif kind == "rect":
            x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
            d = f"M{x:g},{y:g} h{w:g} v{h:g} h{-w:g} z"
        else:
            pts = a["points"].split()
            d = "M" + " L".join(pts) + " z"
        if a.get("fill", "") not in ("", "none"):
            out.append(f'<path android:fillColor="{COLOURS[a["fill"]]}" android:pathData="{d}" />')
        else:
            out.append(f'<path android:strokeColor="{COLOURS[a["stroke"]]}" android:strokeWidth="{a["stroke-width"]}" '
                       f'android:strokeLineCap="butt" android:strokeLineJoin="miter" android:pathData="{d}" />')
    return out


body = "\n            ".join(paths(SRC.read_text()))
height_dp = WIDTH_DP * VH / VW
head = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/wordmark_vectors.py from the R-045 wordmark; do not edit by hand. -->\n'

(RES / "ic_wordmark.xml").write_text(f'''{head}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{WIDTH_DP}dp"
    android:height="{height_dp:.2f}dp"
    android:viewportWidth="{VW}"
    android:viewportHeight="{VH}">
    <group android:translateX="{-X0}" android:translateY="{-Y0}">
            {body}
    </group>
</vector>
''')

# The splash icon (no icon background) is a 288dp canvas whose middle 192dp circle shows; the wordmark sits centred,
# 92dp wide, so the loading screen after it can draw the same wordmark in the same place.
CANVAS = 288
s = WIDTH_DP / VW
(RES / "ic_splash_wordmark.xml").write_text(f'''{head}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{CANVAS}dp"
    android:height="{CANVAS}dp"
    android:viewportWidth="{CANVAS}"
    android:viewportHeight="{CANVAS}">
    <group android:translateX="{(CANVAS - WIDTH_DP) / 2:g}" android:translateY="{(CANVAS - height_dp) / 2:.3f}" android:scaleX="{s:.6f}" android:scaleY="{s:.6f}">
        <group android:translateX="{-X0}" android:translateY="{-Y0}">
            {body}
        </group>
    </group>
</vector>
''')
print("wrote", RES / "ic_wordmark.xml", RES / "ic_splash_wordmark.xml")
